    # Lambda functions in python

# Lambda functions are anonymous functions that can have any number of arguments but only one expression.

# sum of two numbers using lambda function
sum = lambda a, b: a + b
print("The sum is:", sum(10, 20))

# square of a number using lambda function
square = lambda x: x * x
print("The square is:", square(5))

# double of a number using lambda function
double = lambda x: x * 2
print("The double is:", double(10))




