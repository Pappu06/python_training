# Functions in Python

# Greet function
def greet():
    print("Hello, welcome to the program!")
greet()

# Add function
def add(a, b):
    c = a + b
    print("The sum is:", c)

add(10, 20)
add(5, 15)
add(100, 200)


# function with return value
def multiply(x, y):
    return x * y    

result = multiply(5, 10)
print("The product is:", result)

