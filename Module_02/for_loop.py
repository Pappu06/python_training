# For Loop in Python

for i in range(5):
    print("hello")


# range with arguments (start, stop, step)
for i in range(1, 6): # Print numbers from 1 to 5
    print(i)

for i in range(1, 11, 2): # Print odd numbers from 1 to 10
    print(i)

for i in range(10, 0, -1): # Print numbers from 10 to 1
    print(i)