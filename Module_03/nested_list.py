# Nested Lists in Python

matrix = [[1, 2, 3], [4, 5, 6], [7, 8, 9]]
print(matrix)  # Print the nested list (matrix)

# Accessing elements in a nested list
print(matrix[0][0])  # Print the element at the first row and first column
print(matrix[1][1])  # Print the element at the second row and second column
print(matrix[2][2])  # Print the element at the third row and third column

